/**
 * `npm run access:export` — writes the permission catalog for the web app to
 * web-app/src/features/access/generated/catalog.ts (committed). Re-run after
 * any change under backend/src/access/catalog/.
 */
import { mkdirSync, writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import {
  PERMISSION_GROUPS,
  PERMISSION_KEYS,
  PERMISSIONS,
  SCOPES,
} from '../src/access/catalog/permissions';
import { BUNDLES } from '../src/access/catalog/bundles';

/** The web app and the mobile app share one generated catalog. */
const OUTS = [
  resolve(__dirname, '../../web-app/src/features/access/generated/catalog.ts'),
  resolve(__dirname, '../../mobile-app/src/staff/features/access/generated/catalog.ts'),
];
const OUT = OUTS[0];

/** JSON with single quotes and unquoted identifier keys (web-app prettier style). */
function literal(value: unknown, indent = 0): string {
  const pad = '  '.repeat(indent);
  const inner = '  '.repeat(indent + 1);
  if (typeof value === 'string')
    return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (typeof value !== 'object' || value === null) return String(value);
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    return `[\n${value.map((v) => `${inner}${literal(v, indent + 1)},`).join('\n')}\n${pad}]`;
  }
  const entries = Object.entries(value);
  if (!entries.length) return '{}';
  const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : literal(k));
  return `{\n${entries
    .map(([k, v]) => `${inner}${key(k)}: ${literal(v, indent + 1)},`)
    .join('\n')}\n${pad}}`;
}

const features = Object.fromEntries(
  PERMISSION_KEYS.map((k) => [k, PERMISSIONS[k].feature]),
);

const source = `// AUTO-GENERATED by \`npm run access:export\` in backend/ — do not edit.
// Source: backend/src/access/catalog/{permissions,bundles}.ts

export type Scope = 'own' | 'location' | 'org'

export const SCOPES = ${literal(SCOPES)} as const

export const PERMISSION_KEYS = ${literal(PERMISSION_KEYS)} as const

export type Permission = (typeof PERMISSION_KEYS)[number]

/** A role's grant: a scope for scoped permissions, \`true\` otherwise. */
export type Grant = Scope | true

export type PermissionMap = Partial<Record<Permission, Grant>>

export interface PermissionDef {
  feature: string
  label: string
  group: PermissionGroup
  scopes?: readonly Scope[]
  implies?: readonly Permission[]
  risk?: 'high'
}

export const PERMISSION_GROUPS = ${literal(PERMISSION_GROUPS)} as const

export type PermissionGroup = (typeof PERMISSION_GROUPS)[number]

/** Feature that must be on for each permission (\`core\` = always on). */
export const PERMISSION_FEATURES: Record<Permission, string> = ${literal(features)}

export const PERMISSIONS: Record<Permission, PermissionDef> = ${literal(PERMISSIONS)}

export type BundleLevel = 'none' | 'basic' | 'full'

/** Per-module "None / Basic / Full" permission sets for the roles screen. */
export const BUNDLES: Record<
  PermissionGroup,
  Record<BundleLevel, PermissionMap>
> = ${literal(BUNDLES)}
`;

/** Format with the web app's prettier config (web-app's prettier, else backend's). */
async function format(code: string): Promise<string> {
  try {
    const prettierPath = require.resolve('prettier', {
      paths: [resolve(__dirname, '../../web-app'), resolve(__dirname, '..')],
    });
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const prettier = require(prettierPath) as typeof import('prettier');
    const config = (await prettier.resolveConfig(OUT)) ?? {};
    return await prettier.format(code, { ...config, filepath: OUT });
  } catch (err) {
    console.warn(
      `prettier unavailable, writing unformatted: ${(err as Error).message}`,
    );
    return code;
  }
}

void (async () => {
  const formatted = await format(source);
  for (const out of OUTS) {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, formatted);
    console.log(`Wrote ${PERMISSION_KEYS.length} permissions to ${out}`);
  }
})();
