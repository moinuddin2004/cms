// Turns the legal Markdown into the typed content the public web pages render.
// Run from the repo root after editing privacy-policy.md, terms-of-use.md or account-deletion.md:
//   node mobile-app/docs/legal/build-web-content.mjs
// Supported Markdown: # title, ## / ### headings, "- " bullets, "1. " steps, "> " notes, paragraphs,
// **bold**. (No tables.) Output: web-app/src/features/legal/content/legal-content.generated.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(here, '../../../web-app/src/features/legal/content/legal-content.generated.ts')
const FILES = { privacy: 'privacy-policy.md', terms: 'terms-of-use.md', deletion: 'account-deletion.md' }

function parse(md) {
  const blocks = []
  let para = []
  let list = null
  const flushPara = () => {
    if (para.length) blocks.push({ type: 'p', text: para.join(' ') })
    para = []
  }
  const flushList = () => {
    if (list) blocks.push(list)
    list = null
  }
  for (const raw of md.split(/\r?\n/)) {
    const line = raw.trimEnd()
    let m
    if (!line.trim()) {
      flushPara()
      flushList()
    } else if ((m = /^(#{1,3}) (.*)$/.exec(line))) {
      flushPara()
      flushList()
      blocks.push({ type: `h${m[1].length}`, text: m[2] })
    } else if ((m = /^> (.*)$/.exec(line))) {
      flushPara()
      flushList()
      blocks.push({ type: 'note', text: m[1] })
    } else if ((m = /^- (.*)$/.exec(line))) {
      flushPara()
      if (list?.type !== 'ul') {
        flushList()
        list = { type: 'ul', items: [] }
      }
      list.items.push(m[1])
    } else if ((m = /^\d+\. (.*)$/.exec(line))) {
      flushPara()
      if (list?.type !== 'ol') {
        flushList()
        list = { type: 'ol', items: [] }
      }
      list.items.push(m[1])
    } else {
      flushList()
      para.push(line.trim())
    }
  }
  flushPara()
  flushList()
  return blocks
}

const content = Object.fromEntries(
  Object.entries(FILES).map(([k, f]) => [k, parse(readFileSync(resolve(here, f), 'utf8'))]),
)
const ts = `// GENERATED by mobile-app/docs/legal/build-web-content.mjs from the Markdown next to it. Do not edit.
// DRAFT legal text: the owner and a lawyer must review it before publishing.
import type { LegalBlock } from './types'

export const LEGAL_CONTENT: Record<'privacy' | 'terms' | 'deletion', Array<LegalBlock>> = ${JSON.stringify(content, null, 2)}
`
writeFileSync(OUT, ts)
console.log('wrote', OUT)
