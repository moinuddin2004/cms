import { maskPhone } from './mask-phone';

describe('maskPhone', () => {
  it.each([
    ['03001234567', '0300•••4567'],
    ['+923001234567', '+9230•••4567'],
    ['0300-1234567', '0300•••4567'],
    ['+92 300 1234567', '+9230•••4567'],
    ['+92 3001234', '+92•••34'],
    ['123456789', '12•••89'],
    ['+123456789', '+12•••89'],
    ['1234567890', '12•••90'],
    ['12345678', '12•••78'],
    ['1234567', '12•••67'],
    ['12345', '12•••45'],
    ['123456', '12•••56'],
    ['---', ''],
    ['+', ''],
    ['1234', '•••34'],
    ['12', '•••2'],
    ['1', '•••'],
    ['  03001234567  ', '0300•••4567'],
    ['', ''],
    ['   ', ''],
    [null, ''],
    [undefined, ''],
  ])('masks %p as %p', (input, expected) => {
    expect(maskPhone(input)).toBe(expected);
  });
});
